"""Generate the verl tool-config YAML for all WorkBench tools.

Each of the ~27 WorkBench functions is registered as a ``WorkbenchTool`` entry.
The schema is resolved by ``function_name`` at load time (see
``verl.tools.workbench_tool.WorkbenchTool``), so the emitted YAML stays compact
and always in sync with the vendored schemas.

Usage::

    python -m verl.utils.workbench.generate_tool_config \
        --output examples/my_trainer/config/workbench_tool_config.yaml
"""

from __future__ import annotations

import argparse

from verl.utils.workbench.schemas import WORKBENCH_TOOL_NAMES

_HEADER = (
    "# Auto-generated by verl/utils/workbench/generate_tool_config.py\n"
    "# One entry per WorkBench function; schemas are resolved from\n"
    "# verl.utils.workbench.schemas via `function_name` at load time.\n"
)


def build_yaml() -> str:
    lines = [_HEADER, "tools:"]
    for name in WORKBENCH_TOOL_NAMES:
        lines.append('  - class_name: "verl.tools.workbench_tool.WorkbenchTool"')
        lines.append("    config:")
        lines.append("      type: native")
        lines.append(f'      function_name: "{name}"')
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        default="examples/my_trainer/config/workbench_tool_config.yaml",
        help="Path to write the generated tool config YAML.",
    )
    args = parser.parse_args()
    with open(args.output, "w") as f:
        f.write(build_yaml())
    print(f"Wrote {len(WORKBENCH_TOOL_NAMES)} WorkBench tools to {args.output}")


if __name__ == "__main__":
    main()
